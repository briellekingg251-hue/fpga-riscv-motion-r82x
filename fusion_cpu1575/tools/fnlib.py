"""Shared definitions for the Fruit Ninja display engine.

Everything here is the single source of truth for constants that must agree
between the asset generator, the Python GPU reference model, the firmware
headers and the RTL (the bg LUTs are emitted as a Verilog include).
"""
from __future__ import annotations

import random

# ---------------------------------------------------------------- geometry
FB_W = 512           # framebuffer width  (scaled 2x -> 1024)
FB_H = 300           # framebuffer height (scaled 2x -> 600)
LCD_W = 1024
LCD_H = 600
SPR_SIZE = 64        # sprite images are 64x64, 8bpp indexed, 0 = transparent
SPR_SLOTS = 32
GLYPH_W = 16
GLYPH_H = 16

# ---------------------------------------------------------------- palette map
PAL_UI_BASE = 0      # 0..15  fixed UI colours
PAL_BG_BASE = 16     # 16..47 wood: 4 vignette levels x 8 shades
PAL_FX_BASE = 48     # 48..63 effect ramps
PAL_SPR_BASE = 64    # 64..255 sprite colours
PAL_SPR_COUNT = 192

UI_COLORS = [
    ("BLACK",      (0, 0, 0)),
    ("WHITE",      (255, 255, 255)),
    ("INK",        (18, 12, 8)),
    ("RED",        (232, 38, 28)),
    ("GOLD",       (255, 204, 44)),
    ("BLADE_CORE", (235, 250, 255)),
    ("BLADE_GLOW", (120, 200, 255)),
    ("ORANGE",     (255, 140, 20)),
    ("GREEN",      (84, 204, 64)),
    ("DARK_RED",   (122, 12, 10)),
    ("GRAY",       (150, 150, 150)),
    ("DARK_GRAY",  (60, 60, 60)),
    ("SHADOW",     (44, 22, 8)),
    ("CREAM",      (255, 240, 200)),
    ("LIGHT_YELLOW", (255, 250, 150)),
    ("BLUE",       (40, 90, 230)),
]

# blade trail ramp (outer glow -> core) and fire ramp
FX_BLADE = [(40, 80, 170), (60, 120, 220), (90, 160, 250), (130, 200, 255),
            (170, 225, 255), (205, 240, 255), (230, 250, 255), (255, 255, 255)]
FX_FIRE = [(90, 10, 0), (160, 30, 0), (220, 70, 0), (255, 120, 10),
           (255, 170, 30), (255, 210, 70), (255, 240, 150), (255, 255, 230)]

WOOD_SHADES = [(34, 18, 9), (66, 36, 17), (92, 52, 25), (114, 66, 33),
               (134, 80, 41), (153, 95, 50), (174, 112, 61), (198, 133, 76)]
VIGNETTE = [1.00, 0.88, 0.76, 0.63]

# ---------------------------------------------------------------- background
# LUTs are generated from a fixed seed so Python, C and Verilog agree.
_rng = random.Random(20260929)
BG_SEED = [_rng.randrange(256) for _ in range(8)]
BG_WAVE = [int(round(3 + 3 * __import__("math").sin(2 * __import__("math").pi * i / 64)))
           for i in range(64)]                     # 0..6
def _make_grain():
    g = []
    i = 0
    while len(g) < 64:
        run = _rng.choice([1, 1, 2, 2, 3, 4, 5])
        val = _rng.choice([2, 2, 2, 2, 3, 1, 1, 0])  # code: offset = code - 2
        g.extend([val] * run)
        i += 1
    return g[:64]
BG_GRAIN = _make_grain()
BG_JOINT = [_rng.randrange(24, 280) if _rng.random() < 0.75 else 511 for _ in range(8)]
BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
VIG_DITHER = 320
VIG_T = (11000, 19000, 27500)


def bg_index(x: int, y: int, variant: int = 0) -> int:
    """Palette index of the procedural wood background at framebuffer (x, y).

    Integer-only, mirrored bit-for-bit by rtl/video/fn_bg_gen.v.
    """
    p = (x >> 6) & 7
    lx = x & 63
    v4 = variant & 15
    s = BG_SEED[p] ^ ((v4 << 4) | v4)
    wv = BG_WAVE[((y >> 2) + (s & 63)) & 63]
    gi = (lx + wv + (s >> 2)) & 63
    base = 3 + (s & 1) + ((s >> 1) & 1)
    if lx == 0:
        shade = 0
    elif lx == 1:
        shade = 1
    elif lx == 63:
        shade = 7 if base >= 5 else base + 2
    else:
        shade = base + BG_GRAIN[gi] - 2
        shade = 1 if shade < 1 else (7 if shade > 7 else shade)
    jy = BG_JOINT[p]
    if y == jy:
        shade = 0
    elif y == jy + 1:
        shade = 2
    dxc = (x - 256) if x >= 256 else (255 - x)
    dyc = (y - 150) if y >= 150 else (149 - y)
    d = ((dxc * dxc) >> 2) + dyc * dyc + BAYER4[y & 3][x & 3] * VIG_DITHER
    if d < VIG_T[0]:
        lvl = 0
    elif d < VIG_T[1]:
        lvl = 1
    elif d < VIG_T[2]:
        lvl = 2
    else:
        lvl = 3
    return PAL_BG_BASE + lvl * 8 + shade


def base_palette() -> list[tuple[int, int, int]]:
    """Palette entries 0..63 (UI + background + FX). Sprites fill 64..255."""
    pal = [c for _, c in UI_COLORS]
    for lvl in range(4):
        f = VIGNETTE[lvl]
        for r, g, b in WOOD_SHADES:
            pal.append((int(r * f), int(g * f), int(b * f)))
    pal.extend(FX_BLADE)
    pal.extend(FX_FIRE)
    assert len(pal) == PAL_SPR_BASE
    return pal


def verilog_bg_lut() -> str:
    """Verilog include with the background LUT functions."""
    out = ["// Generated by tools/fnlib.py -- do not edit.",
           "function [7:0] bg_seed; input [2:0] i;",
           "  case (i)"]
    for i, v in enumerate(BG_SEED):
        out.append(f"    3'd{i}: bg_seed = 8'd{v};")
    out += ["    default: bg_seed = 8'd0;", "  endcase", "endfunction",
            "function [2:0] bg_wave; input [5:0] i;", "  case (i)"]
    for i, v in enumerate(BG_WAVE):
        out.append(f"    6'd{i}: bg_wave = 3'd{v};")
    out += ["    default: bg_wave = 3'd0;", "  endcase", "endfunction",
            "function [1:0] bg_grain; input [5:0] i;", "  case (i)"]
    for i, v in enumerate(BG_GRAIN):
        out.append(f"    6'd{i}: bg_grain = 2'd{v};")
    out += ["    default: bg_grain = 2'd2;", "  endcase", "endfunction",
            "function [8:0] bg_joint; input [2:0] i;", "  case (i)"]
    for i, v in enumerate(BG_JOINT):
        out.append(f"    3'd{i}: bg_joint = 9'd{v};")
    out += ["    default: bg_joint = 9'd511;", "  endcase", "endfunction",
            "function [3:0] bg_bayer; input [1:0] y; input [1:0] x;",
            "  case ({y, x})"]
    for yy in range(4):
        for xx in range(4):
            out.append(f"    4'd{yy * 4 + xx}: bg_bayer = 4'd{BAYER4[yy][xx]};")
    out += ["    default: bg_bayer = 4'd0;", "  endcase", "endfunction",
            f"localparam integer BG_VIG_DITHER = {VIG_DITHER};",
            f"localparam integer BG_VIG_T0 = {VIG_T[0]};",
            f"localparam integer BG_VIG_T1 = {VIG_T[1]};",
            f"localparam integer BG_VIG_T2 = {VIG_T[2]};",
            f"localparam integer BG_PAL_BASE = {PAL_BG_BASE};", ""]
    return "\n".join(out)


def write_hex(path, values, digits):
    with open(path, "w", newline="\n") as f:
        for v in values:
            f.write(f"{v:0{digits}x}\n")


def read_hex(path):
    with open(path) as f:
        return [int(line, 16) for line in f if line.strip()]

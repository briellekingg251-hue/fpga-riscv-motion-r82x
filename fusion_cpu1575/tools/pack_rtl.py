INC_DIRS = [ROOT / "rtl" / "video", ROOT / "build"]
INC_RE = re.compile(r'^\s*`include\s+"([^"]+)"', re.M)


def expand(path: Path, seen: set[str]) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")

    def repl(m: re.Match) -> str:
        name = m.group(1)
        for d in [path.parent, *INC_DIRS]:
            cand = d / name
            if cand.exists():
                if name in seen and name == "fn_paths.vh":
                    return f"// (fn_paths.vh already included)"
                seen.add(name)
                return f"// ---- begin include {name}\n{expand(cand, seen)}\n// ---- end include {name}"
        raise SystemExit(f"{path}: include {name} not found")

    return INC_RE.sub(repl, text)


def main() -> None:
    seen: set[str] = set()
    parts = ["// Generated by tools/pack_rtl.py -- synthesis input for PDS.\n"]
    for s in SOURCES:
        parts.append(f"\n// ======================================== {s}\n")
        parts.append(expand(ROOT / s, seen))
    out = ROOT / "build" / "fn_design.v"
    out.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({sum(p.count(chr(10)) for p in parts)} lines)")


if __name__ == "__main__":
    main()
